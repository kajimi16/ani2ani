const displayName = (localStorage.getItem("displayName") || "").trim().slice(0, 24);

// Stable identity for this browser. peerId is regenerated by the P2P engine on
// every load, so the server groups participants by this instead — otherwise one
// reload showed the same person twice in the room list.
const viewerId = (() => {
  try {
    const saved = localStorage.getItem("viewer-id");
    if (saved) return saved;
    // crypto.randomUUID needs a secure context; the campus URL is plain http, so
    // fall back to getRandomValues, which works everywhere.
    const bytes = new Uint8Array(16);
    crypto.getRandomValues(bytes);
    const id = [...bytes].map((b) => b.toString(16).padStart(2, "0")).join("");
    localStorage.setItem("viewer-id", id);
    return id;
  } catch {
    return null;
  }
})();

